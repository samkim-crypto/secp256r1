//! Cryptographic constants for the secp256r1 curve and signatures.

/// The size of a compressed secp256r1 public key: a one-byte parity prefix
/// (`0x02` or `0x03`) followed by the 32-byte big-endian X-coordinate.
pub const COMPRESSED_PUBKEY_SERIALIZED_SIZE: usize = 33;

/// The standard length of a serialized secp256r1 signature (r and s concatenated)
pub const SIGNATURE_SERIALIZED_SIZE: usize = 64;

/// The byte length of a single secp256r1 scalar (e.g., the length of 'r' or 's')
pub const SCALAR_BYTES: usize = 32;

/// The group order of the secp256r1 curve (N).
pub const SECP256R1_ORDER: [u8; SCALAR_BYTES] = [
    0xff, 0xff, 0xff, 0xff, 0x00, 0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
    0xbc, 0xe6, 0xfa, 0xad, 0xa7, 0x17, 0x9e, 0x84, 0xf3, 0xb9, 0xca, 0xc2, 0xfc, 0x63, 0x25, 0x51,
];

